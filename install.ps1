# ==============================================================================
# JP Cloud - Windows installer for LOCAL DEVELOPMENT (Docker Desktop, WSL2 backend).
# Production servers use install.sh on Linux.
#
#   .\install.ps1 [-Size auto|small|medium|large|xlarge] [-Monitoring]
#
# * generates a complete .env with fresh random secrets (never overwrites an existing .env; only adds missing keys)
# * local settings: ROOT_DOMAIN=jp.localhost (browsers resolve *.localhost to 127.0.0.1), no TLS, panel on http://localhost:3000
# * runtime/worker run as root inside Docker Desktop (the dev override); everything else is hardened as in production
# * waits for the gateway /healthz and the dashboard and prints the URL
# ==============================================================================
param(
    [ValidateSet("auto", "small", "medium", "large", "xlarge")]
    [string]$Size = "auto",
    [switch]$Monitoring
)
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $Root

function New-RandomBytes([int]$Bytes) {
    $b = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($b)
    return , $b
}
function New-HexSecret([int]$Bytes) { return ((New-RandomBytes $Bytes | ForEach-Object { $_.ToString("x2") }) -join "") }
function New-B64Secret([int]$Bytes) { return [Convert]::ToBase64String((New-RandomBytes $Bytes)) }

Write-Host "==> checking prerequisites" -ForegroundColor Cyan
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { throw "Docker is not installed. Install Docker Desktop and re-run." }
& docker info *> $null
if ($LASTEXITCODE -ne 0) { throw "The Docker engine is not running. Start Docker Desktop and re-run." }
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) { throw "Docker Compose v2 is required (docker compose)." }

$envFile = Join-Path $Root ".env"
$existing = @{}
$created = $false
if (Test-Path $envFile) {
    Write-Host "==> existing .env found - keeping it (only missing keys are added)" -ForegroundColor Cyan
    foreach ($l in Get-Content $envFile) { if ($l -match '^([A-Z0-9_]+)=(.*)$') { $existing[$Matches[1]] = $Matches[2] } }
} else {
    $created = $true
    [System.IO.File]::WriteAllText($envFile, "# JP Cloud local development - generated by install.ps1. Contains secrets, never commit.`n", (New-Object System.Text.UTF8Encoding($false)))
}

$dashPw = New-HexSecret 12
$sha1 = [System.Security.Cryptography.SHA1]::Create().ComputeHash([Text.Encoding]::UTF8.GetBytes($dashPw))
$defaults = [ordered]@{
    "JP_ENV"                     = "production"
    "JP_LOG_LEVEL"               = "info"
    "ROOT_DOMAIN"                = "jp.localhost"
    "MANAGEMENT_DOMAIN"          = ""
    "PUBLIC_BASE_URL"            = "http://localhost:3000"
    "CORS_ORIGINS"               = "http://localhost:3000,http://localhost"
    "PUBLIC_IP"                  = "127.0.0.1"
    "PREVIEW_BASE_DOMAIN"        = "preview.jp.localhost"
    "DOMAIN_CNAME_TARGET"        = "cname.jp.localhost"
    "TLS_ENABLED"                = "false"
    "REGISTRATION_MODE"          = "open"
    "DASHBOARD_BIND"             = "127.0.0.1"
    "DOCKER_GID"                 = "0"
    "JWT_SECRET"                 = (New-HexSecret 24)
    "INTERNAL_TOKEN"             = (New-HexSecret 32)
    "SECRETS_MASTER_KEY"         = (New-B64Secret 32)
    "AI_ENC_KEY"                 = (New-B64Secret 32)
    "IDENTITY_ENC_KEY"           = (New-B64Secret 32)
    "REPO_ENC_KEY"               = (New-B64Secret 32)
    "POSTGRES_USER"              = "jp"
    "POSTGRES_DB"                = "jp"
    "POSTGRES_PASSWORD"          = (New-HexSecret 24)
    "REDIS_PASSWORD"             = (New-HexSecret 24)
    "REGISTRY_HTTP_SECRET"       = (New-HexSecret 16)
    "MINIO_ROOT_USER"            = ("jp" + (New-HexSecret 5))
    "MINIO_ROOT_PASSWORD"        = (New-HexSecret 24)
    "GITHUB_WEBHOOK_SECRET"      = (New-HexSecret 24)
    "GRAFANA_ADMIN_PASSWORD"     = (New-HexSecret 12)
    "TRAEFIK_DASHBOARD_AUTH"     = ("'admin:{SHA}" + [Convert]::ToBase64String($sha1) + "'")
    "TRAEFIK_DASHBOARD_PASSWORD" = $dashPw
}
if ($Monitoring) { $defaults["COMPOSE_PROFILES"] = "monitoring" }
$added = @()
foreach ($k in $defaults.Keys) {
    if (-not $existing.ContainsKey($k)) {
        [System.IO.File]::AppendAllText($envFile, "$k=$($defaults[$k])`n", (New-Object System.Text.UTF8Encoding($false)))
        $added += $k
    }
}
$verb = if ($created) { "created" } else { "updated" }
Write-Host "==> .env $verb ($($added.Count) keys added)" -ForegroundColor Green

Write-Host "==> starting the stack (first build takes several minutes)" -ForegroundColor Cyan
& "$Root\scripts\jp-up.ps1" -Size $Size -Dev -Monitoring:$Monitoring

Write-Host "==> waiting for the gateway and the dashboard" -ForegroundColor Cyan
$gwOk = $false; $uiOk = $false
for ($i = 0; $i -lt 100; $i++) {
    if (-not $gwOk) {
        try { Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 "http://127.0.0.1:8000/healthz" | Out-Null; $gwOk = $true; Write-Host " ok gateway /healthz" -ForegroundColor Green } catch { }
    }
    if (-not $uiOk) {
        try { Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 "http://127.0.0.1:3000/" | Out-Null; $uiOk = $true; Write-Host " ok dashboard" -ForegroundColor Green } catch { }
    }
    if ($gwOk -and $uiOk) { break }
    Start-Sleep -Seconds 3
}
if (-not ($gwOk -and $uiOk)) {
    Write-Warning "not healthy yet. Check: docker compose ps  and  docker compose logs --tail=80 gateway (scripts\jp-up.ps1 prints the exact compose files)"
    exit 1
}
Write-Host ""
Write-Host "JP Cloud (local) is running: http://localhost:3000" -ForegroundColor Green
Write-Host "Register the first account - it becomes the platform administrator."
Write-Host "Secrets are in .env (do not commit). Stop with .\uninstall.ps1"
