#!/usr/bin/env bash
# Detect host RAM/CPU and write .env.resources (tier, worker scale, sizing overlay).
# Usage: scripts/size-host.sh [auto|small|medium|large|xlarge]
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FORCED="${1:-auto}"

have_cmd() { command -v "$1" >/dev/null 2>&1; }

ram_gb() {
  if [[ -r /proc/meminfo ]]; then
    awk '/MemTotal/ {printf "%.1f", $2/1024/1024}' /proc/meminfo
  elif have_cmd sysctl && sysctl -n hw.memsize >/dev/null 2>&1; then
    awk -v b="$(sysctl -n hw.memsize)" 'BEGIN{printf "%.1f", b/1024/1024/1024}'
  else
    echo 8.0
  fi
}

cpus() {
  if have_cmd nproc; then
    nproc
  elif have_cmd sysctl && sysctl -n hw.ncpu >/dev/null 2>&1; then
    sysctl -n hw.ncpu
  else
    echo 2
  fi
}

RAM="$(ram_gb)"
CPUS="$(cpus)"

if [[ "$FORCED" != "auto" ]]; then
  TIER="$FORCED"
else
  TIER="$(awk -v r="$RAM" 'BEGIN{ if (r < 6) print "small"; else if (r < 16) print "medium"; else if (r < 32) print "large"; else print "xlarge" }')"
fi

case "$TIER" in
  small)  REPLICAS=1; CONC=1 ;;
  medium) REPLICAS=1; CONC=2 ;;
  large)  REPLICAS=2; CONC=2 ;;
  xlarge) REPLICAS=2; CONC=4 ;;
  *) echo "unknown tier: $TIER (use auto|small|medium|large|xlarge)" >&2; exit 1 ;;
esac

OUT="$ROOT/.env.resources"
cat >"$OUT" <<EOT
# Generated by scripts/size-host.sh - safe to delete/regenerate. Contains no secrets.
# Host: ${RAM} GB RAM, ${CPUS} logical CPUs
JP_SIZE=${TIER}
JP_HOST_RAM_GB=${RAM}
JP_HOST_CPUS=${CPUS}
WORKER_REPLICAS=${REPLICAS}
WORKER_CONCURRENCY=${CONC}
COMPOSE_SIZING_FILE=infra/compose/sizing/${TIER}.yml
EOT
echo "jp sizing: ${TIER} (${RAM} GB RAM, ${CPUS} CPUs) -> worker x${REPLICAS}, concurrency ${CONC}/worker"
if awk -v r="$RAM" 'BEGIN{exit !(r < 3.5)}'; then
  echo "WARNING: less than 4 GB RAM detected; the full platform needs about 4 GB (add swap or use a bigger host)." >&2
fi
