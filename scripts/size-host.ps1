# Detect host RAM/CPU and write .env.resources (tier, worker scale, sizing overlay).
# Usage: .\scripts\size-host.ps1 [-Size auto|small|medium|large|xlarge]
param(
    [ValidateSet("auto", "small", "medium", "large", "xlarge")]
    [string]$Size = "auto"
)
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)

$cs = Get-CimInstance Win32_ComputerSystem
$ram = [math]::Round($cs.TotalPhysicalMemory / 1GB, 1)
$cpus = [int]$cs.NumberOfLogicalProcessors

if ($Size -ne "auto") { $tier = $Size }
elseif ($ram -lt 6) { $tier = "small" }
elseif ($ram -lt 16) { $tier = "medium" }
elseif ($ram -lt 32) { $tier = "large" }
else { $tier = "xlarge" }

switch ($tier) {
    "small"  { $replicas = 1; $conc = 1 }
    "medium" { $replicas = 1; $conc = 2 }
    "large"  { $replicas = 2; $conc = 2 }
    "xlarge" { $replicas = 2; $conc = 4 }
}

$lines = @(
    "# Generated by scripts/size-host.ps1 - safe to delete/regenerate. Contains no secrets.",
    "# Host: $ram GB RAM, $cpus logical CPUs",
    "JP_SIZE=$tier",
    "JP_HOST_RAM_GB=$ram",
    "JP_HOST_CPUS=$cpus",
    "WORKER_REPLICAS=$replicas",
    "WORKER_CONCURRENCY=$conc",
    "COMPOSE_SIZING_FILE=infra/compose/sizing/$tier.yml"
)
[System.IO.File]::WriteAllText("$Root\.env.resources", (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "jp sizing: $tier ($ram GB RAM, $cpus CPUs) -> worker x$replicas, concurrency $conc/worker"
if ($ram -lt 3.5) { Write-Warning "less than 4 GB RAM detected; the full platform needs about 4 GB." }
