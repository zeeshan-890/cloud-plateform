#!/usr/bin/env bash
# Generate docs/ENVIRONMENT.md from the code: which service reads which variable, what compose passes, and the
# description written above each variable in .env.example.
#   scripts/gen-env-docs.sh > docs/ENVIRONMENT.md
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
PY=python3
if ! python3 -c 'import sys' >/dev/null 2>&1; then PY=python; fi
TMP_JSON="$(mktemp)"
trap 'rm -f "$TMP_JSON"' EXIT
docker compose -f infra/compose/docker-compose.yml -f infra/compose/docker-compose.dev.yml \
  --env-file infra/compose/dev.env --profile monitoring --profile dev config --format json >"$TMP_JSON"

"$PY" - "$ROOT" "$TMP_JSON" <<'PYEOF'
import json, os, re, sys
root, cfg_path = sys.argv[1], sys.argv[2]
services = json.load(open(cfg_path, encoding="utf-8"))["services"]
alias = {"registry": "registry-api"}
call_re = re.compile(r'[A-Za-z_.]*(?:[Ee]nv|Getenv|LookupEnv)[A-Za-z0-9_]*\(([^()]*(?:\([^()]*\)[^()]*)*)\)')
name_re = re.compile(r'"([A-Z][A-Z0-9_]{2,})"')

def scan(base):
    out = {}
    for dp, dn, fn in os.walk(base):
        dn[:] = [d for d in dn if d not in ("node_modules", "vendor", ".git")]
        for f in fn:
            if f.endswith(".go") and not f.endswith("_test.go"):
                for m in call_re.finditer(open(os.path.join(dp, f), encoding="utf-8", errors="replace").read()):
                    for n in name_re.findall(m.group(1)):
                        out.setdefault(n, set())
    return out

readers = {}
for d in sorted(os.listdir(os.path.join(root, "services"))):
    base = os.path.join(root, "services", d)
    if os.path.exists(os.path.join(base, "go.mod")):
        for v in scan(base):
            readers.setdefault(v, set()).add(alias.get(d, d))
for v in scan(os.path.join(root, "packages")):
    readers.setdefault(v, set()).add("(all, via go-common)")

desc, cur, section = {}, [], ""
for line in open(os.path.join(root, ".env.example"), encoding="utf-8"):
    line = line.rstrip("\n")
    m = re.match(r"^#?\s*([A-Z][A-Z0-9_]*)=(.*)$", line)
    if m:
        desc.setdefault(m.group(1), (" ".join(cur), m.group(2)))
        cur = []
    elif line.startswith("# ===="):
        cur = []
    elif line.startswith("#"):
        cur.append(line.lstrip("# ").strip())
    else:
        cur = []

passed = {}
for name, s in services.items():
    for k in (s.get("environment") or {}):
        passed.setdefault(k, set()).add(name)

print("# Environment variable reference\n")
print("Generated by `scripts/gen-env-docs.sh` from the Go sources and the compose files - do not edit by hand.")
print("`install.sh` writes a complete `.env`; `.env.example` explains every value. Required variables make compose refuse to start.\n")
print("| Variable | Read by | Default / example | Description |")
print("|---|---|---|---|")
names = sorted(set(readers) | set(desc) | set(passed))
for n in names:
    r = ", ".join(sorted(readers.get(n, []))) or "compose / infra only"
    if len(r) > 90:
        r = f"{len(readers[n])} services"
    d, default = desc.get(n, ("", ""))
    default = default.strip() or ""
    secretish = re.search(r"(SECRET|PASSWORD|TOKEN|_KEY|AUTH)$", n) and not n.endswith(("_KEYS_PATH", "_KEY_PATH"))
    default = "(generated)" if secretish and not default else default
    print(f"| `{n}` | {r} | {('`'+default+'`') if default and not default.startswith('(') else default} | {d.replace('|','/')} |")
PYEOF
