#!/usr/bin/env bash
# Back up everything that cannot be rebuilt from git.
#
#   scripts/backup.sh [--dir DIR] [--keep N] [--with-tenant-volumes] [--with-registry] [--quiet]
#
# Writes DIR/jp-backup-<UTC timestamp>/ (default DIR: $BACKUP_DIR or ./backups) containing
#   postgres.dump        pg_dump -Fc of the platform database (users, orgs, projects, encrypted secrets, domains, ...)
#   minio.tar.gz         the MinIO data volume (storage buckets of all projects)
#   env.backup           a copy of .env  (contains SECRETS_MASTER_KEY: without it stored secrets are unreadable!)
#   acme.tar.gz          Traefik's Let's Encrypt state (avoids re-issuing certificates / rate limits)
#   traefik_dynamic.tar.gz  generated routers (regenerated by the domain service; kept for convenience)
#   tenant-volumes/*.tar.gz  (--with-tenant-volumes) add-on / managed database volumes, one per volume
#   registry.tar.gz      (--with-registry) built images; normally just rebuild instead
#   MANIFEST.sha256, backup.json
# and then VERIFIES the result (pg_restore --list, tar -t, sha256). Exit code != 0 means the backup is not usable.
# Set BACKUP_PASSPHRASE to AES-256 encrypt env.backup (the only file with plaintext secrets).
#
# NOT included: tenant application containers (redeploy them), Redis (queues/cache), Docker images.
# Volume snapshots of running MinIO/add-on containers are crash-consistent, not transactionally consistent.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=scripts/lib.sh
source "$ROOT/scripts/lib.sh"

DEST="${BACKUP_DIR:-$ROOT/backups}"
KEEP=0 TENANT=0 REGISTRY=0 QUIET=0
while (($#)); do
  case "$1" in
    --dir) DEST="${2:?}"; shift ;;
    --keep) KEEP="${2:?}"; shift ;;
    --with-tenant-volumes) TENANT=1 ;;
    --with-registry) REGISTRY=1 ;;
    --quiet) QUIET=1 ;;
    -h|--help) sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $1" ;;
  esac
  shift
done
say() { if ((QUIET)); then return 0; fi; log "$@"; }

[[ -f "$ROOT/.env" ]] || die ".env not found in $ROOT"
jp_docker_cmd
PG_USER="$(env_get POSTGRES_USER || echo jp)"; PG_DB="$(env_get POSTGRES_DB || echo jp)"
jp_compose ps --status running --services 2>/dev/null | grep -qx postgres || die "postgres container is not running"

umask 077
TS="$(date -u +%Y%m%dT%H%M%SZ)"
OUT="$DEST/jp-backup-$TS"
mkdir -p "$OUT"
chmod 700 "$DEST" "$OUT"

vol() { echo "jp_$1"; }   # compose project is named "jp"
tar_volume() { # tar_volume <volume> <outfile>
  "${JP_DOCKER_CMD[@]}" volume inspect "$1" >/dev/null 2>&1 || { warn "volume $1 does not exist, skipping"; return 1; }
  "${JP_DOCKER_CMD[@]}" run --rm -v "$1":/data:ro -v "$OUT":/out busybox:1.37 tar czf "/out/$2" -C /data .
}

say "postgres dump"
jp_compose exec -T postgres pg_dump -U "$PG_USER" -d "$PG_DB" -Fc >"$OUT/postgres.dump"

say "minio data"
tar_volume "$(vol minio_data)" minio.tar.gz || true

say "traefik state"
tar_volume "$(vol traefik_acme)" acme.tar.gz || true
tar_volume "$(vol traefik_dynamic)" traefik_dynamic.tar.gz || true

if ((REGISTRY)); then say "registry"; tar_volume "$(vol registry_data)" registry.tar.gz || true; fi

if ((TENANT)); then
  say "tenant volumes (add-ons / databases)"
  mkdir -p "$OUT/tenant-volumes"
  while read -r v; do
    [[ -n "$v" ]] || continue
    "${JP_DOCKER_CMD[@]}" run --rm -v "$v":/data:ro -v "$OUT/tenant-volumes":/out busybox:1.37 tar czf "/out/$v.tar.gz" -C /data . || warn "failed: $v"
  done < <({ "${JP_DOCKER_CMD[@]}" volume ls -q --filter label=jp.managed=true
            "${JP_DOCKER_CMD[@]}" volume ls -q --filter name=jp-addon-
            "${JP_DOCKER_CMD[@]}" volume ls -q --filter name=jp-db-; } | sort -u)
fi

say "env"
if [[ -n "${BACKUP_PASSPHRASE:-}" ]]; then
  openssl enc -aes-256-cbc -pbkdf2 -salt -pass env:BACKUP_PASSPHRASE -in "$ROOT/.env" -out "$OUT/env.backup.enc"
else
  cp "$ROOT/.env" "$OUT/env.backup"
  warn "env.backup is stored in PLAINTEXT (contains SECRETS_MASTER_KEY). Keep this directory private or set BACKUP_PASSPHRASE."
fi

REV="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
cat >"$OUT/backup.json" <<EOT
{"created_utc":"$TS","git_rev":"$REV","size_tier":"$(env_get JP_SIZE "$ROOT/.env.resources" || echo unknown)","tenant_volumes":$TENANT,"registry":$REGISTRY,"env_encrypted":$([[ -n "${BACKUP_PASSPHRASE:-}" ]] && echo true || echo false)}
EOT
(cd "$OUT" && find . -type f ! -name MANIFEST.sha256 -print0 | sort -z | xargs -0 sha256sum >MANIFEST.sha256)

# ---- verification -------------------------------------------------------------------------------------------------
say "verifying"
FAIL=0
(cd "$OUT" && sha256sum -c --quiet MANIFEST.sha256) || { err "checksum mismatch"; FAIL=1; }
jp_compose exec -T postgres pg_restore --list <"$OUT/postgres.dump" >"$OUT/.toc" || { err "postgres.dump is not a valid pg_dump archive"; FAIL=1; }
TABLES="$(grep -c ' TABLE DATA ' "$OUT/.toc" || true)"; rm -f "$OUT/.toc"
((TABLES > 0)) || { err "postgres.dump contains no table data entries"; FAIL=1; }
for f in "$OUT"/*.tar.gz "$OUT"/tenant-volumes/*.tar.gz; do
  [[ -f "$f" ]] || continue
  tar -tzf "$f" >/dev/null 2>&1 || { err "corrupt archive: $f"; FAIL=1; }
done
((FAIL == 0)) || die "backup verification FAILED: $OUT"
ok "backup verified: $OUT ($(du -sh "$OUT" | cut -f1), $TABLES tables with data)"

if ((KEEP > 0)); then
  mapfile -t old < <(ls -1dt "$DEST"/jp-backup-* 2>/dev/null | tail -n +$((KEEP + 1)))
  for d in "${old[@]}"; do rm -rf -- "$d"; say "pruned $d"; done
fi
echo "$OUT"
