// Item describes a one-click add-on engine in the marketplace catalog.
type Item struct {
	ID             string   `json:"id"`
	Name           string   `json:"name"`
	Category       string   `json:"category"` // database | cache | queue | search | storage | tool
	Description    string   `json:"description"`
	Logo           string   `json:"logo,omitempty"`
	DefaultPort    int      `json:"default_port,omitempty"`
	Scheme         string   `json:"scheme,omitempty"`
	EnvPrefix      string   `json:"env_prefix,omitempty"`
	DefaultImage   string   `json:"default_image,omitempty"`
	SecretKeys     []string `json:"secret_keys"`
	ModesSupported []string `json:"modes_supported"`
}

var (
	mu       sync.RWMutex
	registry = make(map[string]Item)
	order    []string
)

func init() {
	RegisterDefaults()
}

// Register adds or updates an engine in the marketplace catalog.
func Register(it Item) {
	mu.Lock()
	defer mu.Unlock()
	id := strings.ToLower(strings.TrimSpace(it.ID))
	if id == "" {
		return
	}
	it.ID = id
	if _, exists := registry[id]; !exists {
		order = append(order, id)
	}
	registry[id] = it
}

// RegisterMany adds multiple engines.
func RegisterMany(items ...Item) {
	for _, it := range items {
		Register(it)
	}
}

// Get returns the catalog item for an engine ID if registered.
func Get(id string) (Item, bool) {
	mu.RLock()
	defer mu.RUnlock()
	it, ok := registry[strings.ToLower(strings.TrimSpace(id))]
	return it, ok
}

// All returns the registered engine catalog in order.
func All() []Item {
	mu.RLock()
	defer mu.RUnlock()
	out := make([]Item, 0, len(order))
	for _, id := range order {
		if it, ok := registry[id]; ok {
			out = append(out, it)
		}
	}
	return out
}

// ValidEngine reports whether engine is registered in the catalog.
func ValidEngine(engine string) bool {
	_, ok := Get(engine)
	return ok
}

// SecretName builds the primary secret key for an engine + instance name.
func SecretName(engine, name string) string {
	safe := sanitizeName(name)
	it, ok := Get(engine)
	if ok && it.EnvPrefix != "" {
		return it.EnvPrefix + safe
	}

	switch engine {
	case "postgres":
		return "POSTGRES_URL_" + safe
	case "mysql":
		return "MYSQL_URL_" + safe
	case "mariadb":
		return "MARIADB_URL_" + safe
	case "mongodb":
		return "MONGODB_URI_" + safe
	case "redis":
		return "REDIS_URL_" + safe
	case "valkey":
		return "VALKEY_URL_" + safe
	case "rabbitmq":
		return "AMQP_URL_" + safe
	case "kafka":
		return "KAFKA_BROKERS_" + safe
	case "sqlite":
		return "SQLITE_PATH_" + safe
	case "meilisearch":
		return "MEILISEARCH_URL_" + safe
	case "elasticsearch":
		return "ELASTICSEARCH_URL_" + safe
	case "clickhouse":
		return "CLICKHOUSE_URL_" + safe
	case "minio":
		return "S3_ENDPOINT_" + safe
	default:
		cleanEngine := strings.ToUpper(sanitizeName(engine))
		return fmt.Sprintf("%s_URL_%s", cleanEngine, safe)
	}
}

// LoadCatalogDir loads external catalog definition JSON files from a directory.
// This enables drop-in extensibility for new one-click apps without code changes.
func LoadCatalogDir(dir string) error {
	if dir == "" {
		return nil
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		filePath := filepath.Join(dir, entry.Name())
		data, err := os.ReadFile(filePath)
		if err != nil {
			continue
		}
		// Try parsing as single Item first, then []Item
		var single Item
		if err := json.Unmarshal(data, &single); err == nil && single.ID != "" {
			Register(single)
			continue
		}
		var list []Item
		if err := json.Unmarshal(data, &list); err == nil {
			RegisterMany(list...)
		}
	}
	return nil
}

